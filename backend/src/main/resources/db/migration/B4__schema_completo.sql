-- Schema completo na versão 4, aplicado pelo Flyway somente em bancos novos.
-- Bancos com histórico Flyway continuam usando V1-V4; não editar essas migrações.
-- Estrutura baseada nas entidades JPA, com FKs de tenant e usuário PLATAFORMA sem loja.

create table ajustes (
    restaurante_id bigint,
    id bigint not null,
    primary key (id)
);

create table alertas (
    ativo boolean not null,
    visualizado boolean not null,
    data_geracao timestamp(6) not null,
    data_hora_criacao timestamp(6) not null,
    id bigint generated by default as identity,
    lote_id bigint,
    produto_id bigint,
    restaurante_id bigint not null,
    version bigint not null,
    perfil_destino varchar(20) not null check ((perfil_destino in ('ADMIN','COZINHA','NUTRICIONISTA','PLATAFORMA'))),
    tipo varchar(30) not null check ((tipo in ('ESTOQUE_BAIXO','PROXIMO_VENCIMENTO','VENCIDO','BALANCO_PENDENTE','DIFERENCA_ESTOQUE'))),
    mensagem varchar(300) not null,
    primary key (id)
);

create table auditoria (
    ativo boolean not null,
    data_hora timestamp(6),
    data_hora_criacao timestamp(6) not null,
    id bigint generated by default as identity,
    restaurante_id bigint not null,
    version bigint not null,
    tipo varchar(40) not null,
    entidade varchar(60),
    entidade_id varchar(60),
    usuario_nome varchar(120),
    descricao varchar(400),
    primary key (id)
);

create table balanco_categorias (
    balanco_id bigint not null,
    categoria_id bigint not null
);

create table balancos (
    ativo boolean not null,
    data_hora timestamp(6) not null,
    data_hora_criacao timestamp(6) not null,
    id bigint generated by default as identity,
    restaurante_id bigint not null,
    usuario_id bigint,
    version bigint not null,
    status varchar(20) not null check ((status in ('PENDENTE','EM_ANDAMENTO','CONCLUIDO'))),
    tipo varchar(20) not null check ((tipo in ('GERAL','PARCIAL'))),
    primary key (id)
);

create table categorias (
    ativo boolean not null,
    data_hora_criacao timestamp(6) not null,
    id bigint generated by default as identity,
    restaurante_id bigint not null,
    version bigint not null,
    nome varchar(120) not null,
    descricao varchar(500),
    primary key (id)
);

create table cmv_receitas_periodo (
    ativo boolean not null,
    data_fim date not null,
    data_inicio date not null,
    receita_base numeric(18,2),
    data_hora_criacao timestamp(6) not null,
    id bigint generated by default as identity,
    restaurante_id bigint not null,
    version bigint not null,
    primary key (id),
    constraint uk_cmv_receita_tenant_periodo unique (restaurante_id, data_inicio, data_fim)
);

create table configuracoes_balanco (
    ativo boolean not null,
    dia_execucao integer,
    proxima_execucao date,
    data_hora_criacao timestamp(6) not null,
    id bigint generated by default as identity,
    restaurante_id bigint not null,
    version bigint not null,
    periodicidade varchar(20) not null check ((periodicidade in ('DIARIA','SEMANAL','MENSAL'))),
    primary key (id)
);

create table consumos (
    restaurante_id bigint,
    id bigint not null,
    primary key (id)
);

create table desperdicios (
    restaurante_id bigint,
    id bigint not null,
    motivo varchar(40) not null check ((motivo in ('VENCIMENTO','DETERIORACAO','PREPARO_INCORRETO','SOBRA_NAO_APROVEITADA','OUTRO'))),
    descricao_motivo varchar(500),
    primary key (id)
);

create table entradas (
    restaurante_id bigint,
    data_validade date,
    valor_total_pago numeric(18,2) not null,
    id bigint not null,
    unidade_compra varchar(255) not null check ((unidade_compra in ('KG','G','L','ML','UN'))),
    primary key (id)
);

create table itens_balanco (
    ajuste_aplicado boolean not null,
    ativo boolean not null,
    quantidade_fisica numeric(18,3),
    quantidade_sistema numeric(18,3) not null,
    balanco_id bigint not null,
    data_hora_criacao timestamp(6) not null,
    id bigint generated by default as identity,
    produto_id bigint not null,
    restaurante_id bigint not null,
    version bigint not null,
    primary key (id)
);

create table lotes (
    ativo boolean not null,
    data_entrada date,
    data_validade date,
    preco_unitario numeric(18,6) not null,
    quantidade_atual numeric(18,3) not null,
    quantidade_inicial numeric(18,3) not null,
    data_hora_criacao timestamp(6) not null,
    id bigint generated by default as identity,
    produto_id bigint not null,
    restaurante_id bigint not null,
    version bigint not null,
    codigo varchar(50) not null,
    primary key (id),
    constraint uk_lotes_tenant_codigo unique (restaurante_id, codigo)
);

create table movimentacoes (
    ativo boolean not null,
    quantidade numeric(18,3) not null,
    quantidade_anterior numeric(18,3) not null,
    quantidade_posterior numeric(18,3) not null,
    data_hora timestamp(6) not null,
    data_hora_criacao timestamp(6) not null,
    id bigint generated by default as identity,
    item_balanco_id bigint,
    lote_id bigint,
    produto_aberto_id bigint,
    produto_id bigint not null,
    restaurante_id bigint not null,
    usuario_id bigint not null,
    version bigint not null,
    tipo varchar(20) not null check ((tipo in ('AJUSTE','CONSUMO','DESPERDICIO','ENTRADA'))),
    observacao varchar(500),
    primary key (id)
);

create table parametros_cmv (
    ativo boolean not null,
    percentual_ideal numeric(5,2) not null,
    data_atualizacao timestamp(6) not null,
    data_hora_criacao timestamp(6) not null,
    id bigint generated by default as identity,
    restaurante_id bigint not null,
    version bigint not null,
    primary key (id)
);

create table parametros_estoque (
    ativo boolean not null,
    consumo_medio_diario numeric(18,3) not null,
    dias_alerta_vencimento integer not null,
    estoque_maximo numeric(18,3) not null,
    estoque_medio numeric(18,3) not null,
    estoque_minimo numeric(18,3) not null,
    periodo_analise_dias integer not null,
    tempo_reposicao_dias integer not null,
    data_atualizacao timestamp(6),
    data_hora_criacao timestamp(6) not null,
    id bigint generated by default as identity,
    produto_id bigint not null unique,
    restaurante_id bigint not null,
    version bigint not null,
    primary key (id),
    constraint uk_parametros_estoque_tenant_produto unique (restaurante_id, produto_id)
);

create table produtos (
    ativo boolean not null,
    categoria_id bigint not null,
    data_hora_criacao timestamp(6) not null,
    id bigint generated by default as identity,
    restaurante_id bigint not null,
    version bigint not null,
    unidade_medida varchar(20) not null check ((unidade_medida in ('KG','G','L','ML','UN'))),
    codigo_barras varchar(40),
    nome varchar(120) not null,
    primary key (id)
);

create table produtos_abertos (
    ativo boolean not null,
    finalizado boolean not null,
    quantidade_aberta numeric(18,3) not null,
    quantidade_utilizada numeric(18,3) not null,
    data_abertura timestamp(6) not null,
    data_hora_criacao timestamp(6) not null,
    id bigint generated by default as identity,
    lote_id bigint not null,
    restaurante_id bigint not null,
    usuario_id bigint,
    version bigint not null,
    primary key (id)
);

create table restaurantes (
    ativo boolean not null,
    data_hora_criacao timestamp(6) not null,
    id bigint generated by default as identity,
    version bigint not null,
    nome varchar(120) not null,
    primary key (id)
);

create table usuarios (
    ativo boolean not null,
    data_hora_criacao timestamp(6) not null,
    id bigint generated by default as identity,
    restaurante_id bigint,
    version bigint not null,
    perfil varchar(20) not null check ((perfil in ('ADMIN','COZINHA','NUTRICIONISTA','PLATAFORMA'))),
    senha varchar(100) not null,
    nome varchar(120) not null,
    email varchar(254) not null unique,
    primary key (id)
);

