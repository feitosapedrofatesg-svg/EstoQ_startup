create index idx_lote_produto on lotes (produto_id);

create index idx_lote_validade on lotes (data_validade);

create index idx_mov_tipo_data on movimentacoes (tipo, data_hora);

create index idx_mov_lote on movimentacoes (lote_id);

create index idx_mov_produto on movimentacoes (produto_id);

create index idx_produto_categoria on produtos (categoria_id);

create index idx_aberto_finalizado on produtos_abertos (finalizado);

create index idx_aberto_lote on produtos_abertos (lote_id);

