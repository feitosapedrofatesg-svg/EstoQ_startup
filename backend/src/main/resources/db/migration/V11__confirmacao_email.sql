-- Contas atuais continuam com acesso; não são marcadas como confirmadas.
ALTER TABLE usuarios ADD COLUMN confirmacao_email_obrigatoria BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE usuarios ADD COLUMN email_confirmado_em TIMESTAMP(6);

CREATE TABLE confirmacoes_email (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL,
    ativo BOOLEAN NOT NULL,
    data_hora_criacao TIMESTAMP(6) NOT NULL,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
    email VARCHAR(254) NOT NULL,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    expira_em TIMESTAMP(6) NOT NULL
);
CREATE INDEX idx_confirmacoes_email_usuario_data ON confirmacoes_email(usuario_id, data_hora_criacao);
CREATE INDEX idx_confirmacoes_email_expiracao ON confirmacoes_email(expira_em);
