alter table auditoria add column usuario_id bigint;

create table auditoria_plataforma (
    id bigint generated by default as identity primary key,
    version bigint not null,
    ativo boolean not null,
    data_hora_criacao timestamp(6) not null,
    usuario_id bigint not null references usuarios(id),
    restaurante_id bigint not null references restaurantes(id),
    acao varchar(40) not null,
    usuario_alvo_id bigint references usuarios(id)
);
create index idx_auditoria_plataforma_restaurante on auditoria_plataforma (restaurante_id, data_hora_criacao);
